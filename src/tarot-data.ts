function cardFromRow(id: string, image: string, row: CardRow): TarotCard {
  return {
    id,
    image,
    nameZh: row[0],
    nameEn: row[1],
    keywords: row[2].split(','),
    upright: row[3],
    reversed: row[4],
  };
}

